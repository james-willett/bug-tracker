export function handleSummary(data) {
  const checksRate = metricValue(data, "checks", "rate");
  const failedRate = metricValue(data, "http_req_failed", "rate");
  const durationP95 = metricValue(data, "http_req_duration", "p(95)");

  return {
    "k6-report/index.html": renderHtmlReport(data),
    "k6-report/perf-results.json": JSON.stringify(data, null, 2),
    stdout: [
      "Performance test summary",
      `checks rate: ${formatPercent(checksRate)}`,
      `http request failed rate: ${formatPercent(failedRate)}`,
      `http request duration p95: ${formatNumber(durationP95)}ms`,
    ].join("\n"),
  };
}
