import { check, sleep } from "k6";
import http from "k6/http";

export const options = {
  duration: "30s",
  vus: 1,
  thresholds: {
    http_req_failed: ["rate<0.01"], // http errors should be less than 1%
    http_req_duration: ["p(95)<500"], // 95 percent of response times must be below 500ms
  },
};

const BASE_URL = __ENV.BASE_URL || "http://localhost:8080";

function parseJson(body) {
  try {
    return JSON.parse(body);
  } catch (error) {
    return null;
  }
}

export default function () {
  // Health check
  const healthRes = http.get(`${BASE_URL}/api/health`);
  check(healthRes, {
    "health check status is 200": (r) => r.status === 200,
  });

  // Create a new bug
  const payload = JSON.stringify({
    title: `Test Bug ${Date.now()}`,
    description: "This is a test bug created by k6",
    priority: "Medium",
    status: "Open",
  });

  const headers = { "Content-Type": "application/json" };

  const createBugRes = http.post(`${BASE_URL}/api/bugs`, payload, {
    headers,
  });

  check(createBugRes, {
    "create bug status is 201": (r) => r.status === 201,
    "bug has an id": (r) => {
      const body = parseJson(r.body);
      return body !== null && body.id !== undefined;
    },
  });

  sleep(5);
}

function metricValue(data, metricName, valueName) {
  const metric = data.metrics[metricName];
  return metric && metric.values ? metric.values[valueName] : undefined;
}

function formatNumber(value, digits = 2) {
  return value === undefined ? "n/a" : Number(value).toFixed(digits);
}

function formatPercent(value) {
  return value === undefined ? "n/a" : `${(Number(value) * 100).toFixed(2)}%`;
}

function thresholdRows(data) {
  const rows = [];

  Object.keys(data.metrics).forEach((metricName) => {
    const thresholds = data.metrics[metricName].thresholds || {};

    Object.keys(thresholds).forEach((thresholdName) => {
      rows.push(`
        <tr>
          <td>${metricName}</td>
          <td>${thresholdName}</td>
          <td class="${thresholds[thresholdName].ok ? "pass" : "fail"}">
            ${thresholds[thresholdName].ok ? "PASS" : "FAIL"}
          </td>
        </tr>
      `);
    });
  });

  return rows.length
    ? rows.join("")
    : '<tr><td colspan="3">No thresholds were configured.</td></tr>';
}

